  let current = "en";

  function t(key) {
    return (I18N[current] && I18N[current][key]) || I18N.en[key] || key;
  }

  function setLang(lang) {
    current = I18N[lang] ? lang : "en";
    document.documentElement.lang = current;
    applyI18n(document);
  }

  function applyI18n(root) {
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });
  }

  /* Libelle localise d'un manifeste : {en:..., fr:...} ou chaine simple
     Localized manifest label: {en:..., fr:...} or plain string */
  function fromManifest(value) {
    if (value == null) return "";
    if (typeof value === "string") return value;
    return value[current] || value.en || Object.values(value)[0] || "";
  }

  window.PiBoardI18n = { t, setLang, applyI18n, fromManifest, get lang() { return current; } };
