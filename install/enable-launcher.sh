#!/usr/bin/env bash
# ============================================================
# PiBoard - autorise l'icone « PiBoard » du bureau a redemarrer le
# serveur SANS mot de passe (1.180.0). A lancer une seule fois :
#     sudo bash install/enable-launcher.sh
# Ecrit une regle polkit qui permet a l'utilisateur du service de
# redemarrer (et seulement redemarrer) le service piboard.service.
# Sans elle, l'icone fonctionne aussi, mais demande le mot de passe.
#
# Lets the desktop "PiBoard" icon restart the server WITHOUT a password.
# Run once with sudo. Writes a polkit rule allowing the service user to
# restart piboard.service, and nothing else.
# ============================================================
set -euo pipefail

if [[ $EUID -ne 0 ]]; then
  echo "A lancer avec sudo / run with sudo: sudo bash install/enable-launcher.sh" >&2
  exit 1
fi

TARGET_USER="${1:-}"
[[ -z "$TARGET_USER" ]] && TARGET_USER="$(systemctl show piboard.service -p User --value 2>/dev/null || true)"
[[ -z "$TARGET_USER" ]] && TARGET_USER="${SUDO_USER:-pi}"
if ! id "$TARGET_USER" >/dev/null 2>&1; then
  echo "Utilisateur introuvable / user not found: $TARGET_USER" >&2
  exit 1
fi
if [[ ! -d /etc/polkit-1/rules.d ]]; then
  echo "polkit absent : l'icone demandera le mot de passe. / polkit missing: the icon will ask for the password." >&2
  exit 1
fi

RULE=/etc/polkit-1/rules.d/50-piboard-restart.rules
cat > "$RULE" <<POLKIT
// Genere par install/enable-launcher.sh de PiBoard. Autorise
// l'utilisateur du service a redemarrer piboard.service, et rien d'autre.
// Generated by PiBoard's install/enable-launcher.sh. Allows the service
// user to restart piboard.service, and nothing else.
polkit.addRule(function(action, subject) {
  if (action.id == "org.freedesktop.systemd1.manage-units" &&
      action.lookup("unit") == "piboard.service" &&
      (action.lookup("verb") == "restart" || action.lookup("verb") == "start") &&
      subject.user == "$TARGET_USER") {
    return polkit.Result.YES;
  }
});
POLKIT
chmod 644 "$RULE"
systemctl reload polkit 2>/dev/null || systemctl restart polkit 2>/dev/null || true
echo "OK : l'icone PiBoard redemarre le serveur sans mot de passe ($RULE, utilisateur / user: $TARGET_USER)"
